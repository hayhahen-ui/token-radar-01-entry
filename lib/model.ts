const DAY_MS = 86_400_000;

/** A finite number, else `fallback`: a missing or unusable figure scores its default. */
function finite(value: unknown, fallback: number): number {
  if (typeof value !== 'number') return fallback;
  return Number.isFinite(value) ? value : fallback;
}

/** Whole days a protocol has been listed: the calendar gap from its listing date to `asOf`, never below zero; null when either date is absent or unparseable. */
export function ageDays(asOf: string, listedAt: string | null): number | null {
  if (listedAt === null) return null;
  const listed = Date.parse(`${listedAt}T00:00:00Z`);
  const now = Date.parse(`${asOf}T00:00:00Z`);
  if (!Number.isFinite(listed) || !Number.isFinite(now)) return null;
  const days = Math.floor((now - listed) / DAY_MS);
  return days < 0 ? 0 : days;
}

/** The middle value of a list: the centre, or the mean of the two centres; 0 when empty. */
function median(values: number[]): number {
  const sorted = [...values].sort((a, b) => a - b);
  const n = sorted.length;
  if (n === 0) return 0;
  const half = n >> 1;
  return n % 2 === 1 ? sorted[half]! : (sorted[half - 1]! + sorted[half]!) / 2;
}

/**
 * Each category's multiple, from the snapshot's own live-token protocols: the median mcap/TVL of the
 * category's live protocols, divided by the median over every live protocol, clamped to the model's
 * floor and cap. A category with fewer live samples than the model's minimum, and a protocol with no
 * category, scores 1.0. No protocol name is read here, only its category and its two money figures.
 */
export function categoryMultiples(snapshot: Snapshot, model: ModelConstants): Map<string, number> {
  const byCategory = new Map<string, number[]>();
  const all: number[] = [];
  for (const p of snapshot.protocols) {
    if (p.mcap_usd !== null && p.mcap_usd > 0 && p.tvl_usd > 0) {
      const ratio = p.mcap_usd / p.tvl_usd;
      all.push(ratio);
      const key = p.category ?? 'Other';
      const arr = byCategory.get(key) ?? [];
      arr.push(ratio);
      byCategory.set(key, arr);
    }
  }
  const global = median(all);
  const out = new Map<string, number>();
  if (global <= 0) return out;
  for (const [category, ratios] of byCategory) {
    if (ratios.length < model.category_min_samples) continue;
    const raw = median(ratios) / global;
    out.set(category, Math.min(model.category_cap, Math.max(model.category_floor, raw)));
  }
  return out;
}

/** The category multiples as a table, strongest first, for the dashboard's model section. */
export function categoryMultipleTable(snapshot: Snapshot, model: ModelConstants): CategoryMultiple[] {
  const multiples = categoryMultiples(snapshot, model);
  const counts = new Map<string, number>();
  for (const p of snapshot.protocols) {
    if (p.mcap_usd !== null && p.mcap_usd > 0 && p.tvl_usd > 0) {
      const key = p.category ?? 'Other';
      counts.set(key, (counts.get(key) ?? 0) + 1);
    }
  }
  return [...multiples.entries()]
    .map(([category, multiple]) => ({ category, multiple: round4(multiple), samples: counts.get(category) ?? 0 }))
    .sort((a, b) => b.multiple - a.multiple || (a.category < b.category ? -1 : 1));
}

/** The five multipliers and the implied value one protocol gets under `model`. */
export function impliedValue(
  protocol: SnapshotProtocol,
  asOf: string,
  model: ModelConstants,
  multiples: Map<string, number>,
): {
  implied: number;
  baseValue: number;
  categoryMult: number;
  growthPct: number;
  growthMult: number;
  maturityMult: number;
  chainMult: number;
  age: number | null;
} {
  const age = ageDays(asOf, protocol.listed_at);
  const rawGrowth = finite(protocol.change_7d, 0);
  const growthPct = Math.min(model.growth_cap, Math.max(model.growth_floor, rawGrowth));
  const weight = growthPct >= 0 ? model.growth_weight : model.growth_weight_negative;
  const growthMult = 1 + (growthPct / 100) * weight;
  const ageForModel = age ?? model.unknown_age_days;
  const matured = Math.min(Math.max(ageForModel, 0), model.maturity_days);
  const extra = Math.min(Math.max(ageForModel - model.maturity_days, 0), model.longevity_days);
  const maturityMult = model.maturity_floor + (matured / model.maturity_days) * model.maturity_range + (extra / model.longevity_days) * model.longevity_bonus;
  const chainMult = 1 + model.chain_step * Math.min(Math.max(protocol.chains.length - 1, 0), model.chain_max_extra);
  // The multiple the row carries is rounded to 4 places first, so the dashboard's recompute of the
  // row from the stored figures gives exactly the number board.json carries.
  const categoryMult = Math.round((multiples.get(protocol.category ?? 'Other') ?? 1) * 1e4) / 1e4;
  const baseValue = protocol.tvl_usd * model.base_multiple;
  const implied = Math.max(1, Math.round(baseValue * categoryMult * growthMult * maturityMult * chainMult));
  return { implied, baseValue, categoryMult, growthPct, growthMult, maturityMult, chainMult, age };
}

/** DefiLlama's version-marker rule: a name ending in a release is a pool of another protocol. */
const VERSIONED = /\s(V\d+(\.\d+)?|v\d+(\.\d+)?|\d+\.\d+)$/;

/** Whether a protocol records no token at all. */
export function isPreToken(p: SnapshotProtocol): boolean {
  return p.mcap_usd === null && p.gecko_id === null && p.symbol === null;
}

/** Whether a protocol is one the board may rank: pre-token, not an exchange, not a versioned pool. */
export function isRankable(p: SnapshotProtocol): boolean {
  return isPreToken(p) && p.category !== 'CEX' && !VERSIONED.test(p.name);
}

/** The snapshot's protocol by slug. */
function bySlug(protocols: SnapshotProtocol[]): Map<string, SnapshotProtocol> {
  return new Map(protocols.map((p) => [p.slug, p]));
}

/** The headline sentence's figures: how many watchlist slugs, how many rows, how many live protocols. */
export interface BoardSummary {
  watchlist_size: number;
  board_size: number;
  early_size: number;
  live_size: number;
}

/** The protocols the board ranks, strongest first, with ranks 1..n. */
export function buildBoard(snapshot: Snapshot, model: ModelConstants = MODEL): BoardRow[] {
  const multiples = categoryMultiples(snapshot, model);
  const index = bySlug(snapshot.protocols);
  const chosen = new Map<string, SnapshotProtocol>();
  // The watchlist is the floor: every slug, even one the snapshot no longer carries (it cannot, but the
  // board's coverage is the gate's row and is never gambled on a missing record).
  for (const slug of snapshot.watchlist) {
    const p = index.get(slug);
    if (p !== undefined) chosen.set(slug, p);
  }
  // The early radar: pre-token protocols below the watchlist floor, by TVL, capped. Never a replacement
  // for a watchlist row: a chosen protocol stays chosen.
  const early = snapshot.protocols
    .filter((p) => !chosen.has(p.slug) && isRankable(p) && p.tvl_usd < snapshot.floor_usd)
    .sort((a, b) => b.tvl_usd - a.tvl_usd || (a.slug < b.slug ? -1 : a.slug > b.slug ? 1 : 0))
    .slice(0, EARLY_ROWS);
  for (const p of early) chosen.set(p.slug, p);

  const scored = [...chosen.values()].map((p) => {
    const s = impliedValue(p, snapshot.as_of, model, multiples);
    return { p, ...s };
  });
  scored.sort((a, b) => b.implied - a.implied || (a.p.slug < b.p.slug ? -1 : a.p.slug > b.p.slug ? 1 : 0));
  return scored.map((s, i) => ({
    rank: i + 1,
    slug: s.p.slug,
    name: s.p.name,
    category: s.p.category,
    chains: s.p.chains,
    tvl_usd: s.p.tvl_usd,
    change_7d: s.p.change_7d,
    mcap_usd: s.p.mcap_usd,
    listed_at: s.p.listed_at,
    gecko_id: s.p.gecko_id,
    symbol: s.p.symbol,
    token_status: 'pre-token',
    age_days: s.age,
    implied_value_usd: s.implied,
    model: {
      base_multiple: model.base_multiple,
      base_value_usd: Math.round(s.baseValue),
      category_multiple: round4(s.categoryMult),
      growth_pct: s.growthPct,
      growth_multiplier: round4(s.growthMult),
      maturity_multiplier: round4(s.maturityMult),
      chain_multiplier: round4(s.chainMult),
      age_days: s.age,
    },
    farm_steps: farmSteps(s.p, s.age).map(stepText),
  }));
}

const round4 = (n: number): number => Math.round(n * 1e4) / 1e4;

/** A step as one string: its action, then its cost and time, within the gate's 20..600 characters. */
export function stepText(step: FarmStep): string {
  const joined = `${step.text} Cost: ${step.cost}. Time: ${step.time}.`;
  if (joined.length > 600) return `${joined.slice(0, 596)}...`;
  if (joined.length < 20) return `${joined} Hold the position and check the protocol's own page.`;
  return joined;
}

/** The first chain a protocol names, or a neutral phrase when it names none. */
function chainOf(p: SnapshotProtocol): string {
  const first = p.chains[0];
  return first === undefined ? 'its main chain' : first;
}

/** How much capital one farm position needs, from the protocol's own TVL. */
const CAPITAL_TIERS: [floor: number, amount: number][] = [
  [5_000_000_000, 250],
  [1_000_000_000, 150],
  [100_000_000, 100],
];
function capitalFor(p: SnapshotProtocol): number {
  for (const [floor, amount] of CAPITAL_TIERS) {
    if (p.tvl_usd >= floor) return amount;
  }
  return 50;
}

/** How long to hold, from the protocol's age: younger protocols get a longer qualifying window. */
const HOLD_TIERS: [underDays: number, holdDays: number][] = [
  [180, 60],
  [365, 45],
];
function holdDaysFor(age: number | null): number {
  if (age === null) return 30;
  for (const [underDays, holdDays] of HOLD_TIERS) {
    if (age < underDays) return holdDays;
  }
  return 30;
}

/** The category's one action, in the words a farmer can follow. */
function actionFor(p: SnapshotProtocol, capital: number, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) return `Supply $${capital} of USDC to ${name} on ${chain} and keep the position open.`;
  if (c.includes('dex') || c.includes('yield') || c.includes('leveraged farm')) return `Provide $${capital} of liquidity to ${name}'s main pool on ${chain} and keep the position open.`;
  if (c.includes('bridge')) return `Bridge $${capital} of USDC to ${chain} through ${name} and use the bridged funds in its app.`;
  if (c.includes('staking') || c.includes('restak')) return `Stake $${capital} of the chain's staking asset through ${name} and keep the receipt.`;
  if (c.includes('perpetual') || c.includes('derivative')) return `Deposit $${capital} of USDC as margin on ${name} and open one small hedge.`;
  if (c.includes('prediction')) return `Fund $${capital} and place one market position on ${name}.`;
  if (c.includes('curator') || c.includes('allocator')) return `Deposit $${capital} into a ${name} vault on ${chain} and keep the shares.`;
  if (c.includes('stable')) return `Mint or deposit $${capital} of the stable asset through ${name} on ${chain}.`;
  if (c.includes('rwa')) return `Mint $${capital} of the protocol's yield asset on ${chain} and hold it.`;
  if (c.includes('insurance')) return `Buy $${capital} of cover from ${name} on ${chain} and keep the policy.`;
  return `Deposit $${capital} of USDC into ${name} on ${chain} and keep the position open.`;
}

/** The category's weekly qualifying action: the same habit, in the words of what the protocol does. */
function weeklyActionFor(p: SnapshotProtocol, capital: number, chain: string): string {
  const c = (p.category ?? '').toLowerCase();
  const name = p.name;
  if (c.includes('lend') || c.includes('cdp') || c.includes('collateral')) return `Borrow a small amount against the deposit once a week and repay it the same day, so ${name} records a borrower, not only a depositor.`;
  if (c.includes('dex') || c.includes('yield') || c.includes('leveraged farm')) return `Swap a small amount through ${name}'s main pool once a week, alternating the direction, so the pool records a trader as well as a liquidity provider.`;
  if (c.includes('bridge')) return `Bridge a small amount to ${chain} once a week through ${name} and use the bridged funds in its app the same day.`;
  if (c.includes('staking') || c.includes('restak')) return `Claim the staking rewards once a week and restake them through ${name}, so the position grows on record.`;
  if (c.includes('perpetual') || c.includes('derivative')) return `Open and close one small hedge a week on ${name}, so the account shows a trader with volume, not only a deposit.`;
  if (c.includes('prediction')) return `Place one small market position a week on ${name} and settle it, so the account shows repeated use.`;
  if (c.includes('curator') || c.includes('allocator')) return `Deposit a small top-up into the ${name} vault once a week, so the vault records a returning depositor.`;
  if (c.includes('stable')) return `Mint or redeem a small amount of the stable asset once a week through ${name} on ${chain}.`;
  if (c.includes('rwa')) return `Buy a small top-up of the yield asset once a week on ${chain} and hold it with the first position.`;
  if (c.includes('insurance')) return `Check the cover's terms once a week and file a small claim only if a covered event happened.`;
  return `Make one qualifying action each week, such as a deposit, a borrow, a swap or a vote.`;
}

/**
 * A protocol's farm plan: six steps, each an action with a cost and a time. The plan is derived from
 * the protocol's own record (category, chains, TVL, age), never from a hand-written list of names.
 */
export function farmSteps(p: SnapshotProtocol, age: number | null): FarmStep[] {
  const chain = chainOf(p);
  const capital = capitalFor(p);
  const hold = holdDaysFor(age);
  const action = actionFor(p, capital, chain);
  return [
    {
      text: `Use a fresh wallet that holds only the funds you plan to farm, and keep its seed phrase offline.`,
      cost: 'under $3 of gas for the first transaction',
      time: '5 minutes',
    },
    {
      text: action,
      cost: `$${capital} of capital and about $${capital >= 150 ? 8 : 4} of gas on ${chain}`,
      time: '15 minutes to set up',
    },
    {
      text: weeklyActionFor(p, capital, chain),
      cost: `about $2 of gas a week on ${chain}`,
      time: '10 minutes a week',
    },
    {
      text: `Hold the position for at least ${hold} days so the activity is counted in more than one snapshot.`,
      cost: `the $${capital} stays in the position`,
      time: `${hold} days`,
    },
    {
      text: `Before you withdraw, open the protocol's own points or rewards page and claim only from the link it publishes.`,
      cost: 'no fee to check, and never pay to claim',
      time: '10 minutes',
    },
    {
      text: `Write the wallet, the dates and every transaction in a farm log so you can repeat the position or unwind it.`,
      cost: 'nothing but the log',
      time: '5 minutes',
    },
  ];
}

/** The live-token protocols, by market cap, for the dashboard's Live token view. */
export function liveRows(snapshot: Snapshot): LiveRow[] {
  return snapshot.protocols
    .filter((p) => !isPreToken(p) && p.category !== 'CEX')
    .sort((a, b) => (b.mcap_usd ?? 0) - (a.mcap_usd ?? 0) || b.tvl_usd - a.tvl_usd)
    .slice(0, LIVE_ROWS)
    .map((p) => ({
      slug: p.slug,
      name: p.name,
      category: p.category,
      chains: p.chains,
      tvl_usd: p.tvl_usd,
      mcap_usd: p.mcap_usd,
      change_7d: p.change_7d,
    }));
}

